#!/usr/bin/env node
/**
 * Medusa design system build.
 *
 *   node design-system/build/build.mjs
 *
 * Reads the platform-agnostic token JSON in ../tokens and emits:
 *   dist/css/tokens.css            → CSS custom properties (dark default + light override)
 *   dist/react/tokens.ts           → typed TS object + CSS-var helper
 *   dist/flutter/medusa_tokens.dart → Dart constants
 *   dist/flutter/medusa_theme.dart  → ready-made light/dark ThemeData
 *   dist/flutter/medusa_icons.dart  → the shared icon set as drawable primitives
 *
 * Everything under dist/ is generated — never hand-edit it.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const tokensDir = join(root, "tokens")
const distDir = join(root, "dist")

const read = (name) => JSON.parse(readFileSync(join(tokensDir, name), "utf8"))

const color = read("color.json")
const typography = read("typography.json")
const layout = read("layout.json")
const motion = read("motion.json")
const icons = read("icons.json")

const write = (relPath, contents) => {
  const full = join(distDir, relPath)
  mkdirSync(dirname(full), { recursive: true })
  writeFileSync(full, contents, "utf8")
  console.log(`  ✓ dist/${relPath.replace(/\\/g, "/")}`)
}

const BANNER = `Generated by design-system/build/build.mjs — do not edit by hand.\nEdit design-system/tokens/*.json and re-run \`npm run tokens\`.`

/* ── token tree walking ─────────────────────────────────────────── */

/** Yields { path: ["color","bg","0"], token } for every leaf token ($value present). */
function* walk(node, path = []) {
  if (node && typeof node === "object" && "$value" in node) {
    yield { path, token: node }
    return
  }
  for (const [key, child] of Object.entries(node ?? {})) {
    if (key.startsWith("$")) continue
    if (child && typeof child === "object") yield* walk(child, [...path, key])
  }
}

const kebab = (path) => path.join("-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()
const camel = (path) =>
  path
    .map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1)))
    .join("")
    .replace(/[^a-zA-Z0-9]/g, "")

/** Themed tokens carry { dark, light }; flat tokens carry a plain value. */
const isThemed = (v) => v && typeof v === "object" && !Array.isArray(v) && ("dark" in v || "light" in v)
const themed = (v, theme) => (isThemed(v) ? v[theme] ?? v.dark : v)

/* ── CSS ────────────────────────────────────────────────────────── */

/**
 * The app's existing stylesheet expects short names (--bg-0, --fg-1, --accent-hi,
 * --crit, --line-2, --r-md, --font-sans …). These aliases keep the generated
 * output drop-in compatible with it while also emitting the fully-qualified
 * names for anything new.
 */
const CSS_ALIASES = {
  "color-bg-0": "bg-0", "color-bg-1": "bg-1", "color-bg-2": "bg-2", "color-bg-3": "bg-3", "color-bg-4": "bg-4",
  "color-fg-0": "fg-0", "color-fg-1": "fg-1", "color-fg-2": "fg-2", "color-fg-3": "fg-3", "color-fg-4": "fg-4",
  "color-accent-hi": "accent-hi", "color-accent-base": "accent", "color-accent-glow": "accent-glow", "color-accent-soft": "accent-soft",
  "color-crit-base": "crit", "color-crit-soft": "crit-soft",
  "color-cool-base": "cool", "color-cool-soft": "cool-soft",
  "color-warn-base": "warn",
  "color-line-1": "line-1", "color-line-2": "line-2", "color-line-3": "line-3",
  "color-on-accent-base": "on-accent",
  "radius-sm": "r-sm", "radius-md": "r-md", "radius-lg": "r-lg", "radius-pill": "r-pill",
  "font-family-sans": "font-sans", "font-family-mono": "font-mono",
}

function cssValue(name, token, theme) {
  const raw = themed(token.$value, theme)
  if (token.$type === "fontFamily") {
    return raw.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(", ")
  }
  if (token.$type === "cubicBezier") return `cubic-bezier(${raw.join(", ")})`
  if (token.$type === "duration") return `${raw}ms`
  if (token.$type === "dimension") {
    // em-based tracking tokens and unitless ratios stay unitless-aware
    if (name.startsWith("font-tracking")) return `${raw}em`
    return typeof raw === "number" ? `${raw}px` : raw
  }
  return String(raw)
}

function buildCss() {
  const groups = { color, typography, layout, motion }
  const lines = []
  const darkVars = []
  const lightVars = []

  for (const tree of Object.values(groups)) {
    for (const { path, token } of walk(tree)) {
      const name = kebab(path)
      const dark = cssValue(name, token, "dark")
      const light = cssValue(name, token, "light")
      const emit = (bucket, value) => {
        bucket.push(`  --${name}: ${value};`)
        const alias = CSS_ALIASES[name]
        if (alias) bucket.push(`  --${alias}: ${value};`)
      }
      emit(darkVars, dark)
      if (isThemed(token.$value) && light !== dark) emit(lightVars, light)
    }
  }

  lines.push(`/*\n  ${BANNER.split("\n").join("\n  ")}\n*/`)
  lines.push("")
  lines.push(":root {")
  lines.push(...darkVars)
  lines.push("}")
  lines.push("")
  lines.push('/* Light theme — opt in with <html data-theme="light"> */')
  lines.push(':root[data-theme="light"] {')
  lines.push(...lightVars)
  lines.push("}")
  lines.push("")
  lines.push("/* Follow the OS when no explicit choice has been stored. */")
  lines.push("@media (prefers-color-scheme: light) {")
  lines.push("  :root:not([data-theme]) {")
  lines.push(...lightVars.map((l) => `  ${l}`))
  lines.push("  }")
  lines.push("}")
  lines.push("")

  write("css/tokens.css", lines.join("\n") + "\n")
}

/* ── TypeScript ─────────────────────────────────────────────────── */

function tsLiteral(v) {
  return typeof v === "string" ? JSON.stringify(v) : Array.isArray(v) ? JSON.stringify(v) : String(v)
}

function buildTs() {
  const groups = { color, typography, layout, motion }
  const dark = {}
  const light = {}
  const flat = {}

  for (const tree of Object.values(groups)) {
    for (const { path, token } of walk(tree)) {
      const key = camel(path)
      if (isThemed(token.$value)) {
        dark[key] = themed(token.$value, "dark")
        light[key] = themed(token.$value, "light")
      } else {
        flat[key] = token.$value
      }
    }
  }

  const obj = (o) =>
    Object.entries(o)
      .map(([k, v]) => `  ${k}: ${tsLiteral(v)},`)
      .join("\n")

  const out = `/**
 * ${BANNER.split("\n").join("\n * ")}
 */

/** Colours that differ per theme. */
export const darkTheme = {
${obj(dark)}
} as const

export const lightTheme = {
${obj(light)}
} as const

/** Theme-independent tokens (sizing, motion, type ramp). */
export const tokens = {
${obj(flat)}
} as const

export type ThemeName = "dark" | "light"
export type ThemedToken = keyof typeof darkTheme
export type Token = keyof typeof tokens

/** Both themes define the same keys; the values differ, hence the widening. */
export type Palette = { readonly [K in ThemedToken]: string }

export const themes: Record<ThemeName, Palette> = {
  dark: darkTheme,
  light: lightTheme,
}

/**
 * Reference a token through its CSS custom property, so themes still switch at
 * runtime via \`<html data-theme>\` instead of being frozen at render time.
 *
 *   <div style={{ color: cssVar("fg-0") }} />
 */
export const cssVar = (name: string, fallback?: string) =>
  fallback ? \`var(--\${name}, \${fallback})\` : \`var(--\${name})\`
`
  write("react/tokens.ts", out)
}

/* ── Flutter ────────────────────────────────────────────────────── */

/** #rrggbb / rgba(r,g,b,a) → Dart Color(0xAARRGGBB). */
function dartColor(css) {
  const v = String(css).trim()
  let r, g, b, a = 1
  const hex = v.match(/^#([0-9a-f]{6})$/i)
  const rgba = v.match(/^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i)
  if (hex) {
    r = parseInt(hex[1].slice(0, 2), 16)
    g = parseInt(hex[1].slice(2, 4), 16)
    b = parseInt(hex[1].slice(4, 6), 16)
  } else if (rgba) {
    r = +rgba[1]; g = +rgba[2]; b = +rgba[3]; a = rgba[4] !== undefined ? +rgba[4] : 1
  } else {
    return null
  }
  const A = Math.round(a * 255).toString(16).padStart(2, "0")
  const toHex = (n) => Math.round(n).toString(16).padStart(2, "0")
  return `Color(0x${A}${toHex(r)}${toHex(g)}${toHex(b)})`
}

const dartName = (path) => {
  const n = camel(path)
  return n.charAt(0).toLowerCase() + n.slice(1)
}

function buildFlutter() {
  const colorLines = { dark: [], light: [] }
  for (const { path, token } of walk(color)) {
    const name = dartName(path.slice(1)) // drop leading "color"
    for (const theme of ["dark", "light"]) {
      const c = dartColor(themed(token.$value, theme))
      if (c) colorLines[theme].push(`  static const ${name} = ${c};`)
    }
  }

  const dims = []
  for (const tree of [layout, typography]) {
    for (const { path, token } of walk(tree)) {
      if (token.$type === "dimension" || token.$type === "number") {
        const v = themed(token.$value, "dark")
        if (typeof v === "number") dims.push(`  static const ${dartName(path)} = ${v.toFixed(v % 1 === 0 ? 1 : 2)};`)
      }
      if (token.$type === "fontWeight") {
        dims.push(`  static const ${dartName(path)} = FontWeight.w${themed(token.$value, "dark")};`)
      }
    }
  }

  const durations = []
  for (const { path, token } of walk(motion)) {
    if (token.$type === "duration") {
      durations.push(`  static const ${dartName(path.slice(1))} = Duration(milliseconds: ${token.$value});`)
    }
    if (token.$type === "cubicBezier") {
      const [a, b, c, d] = token.$value
      durations.push(`  static const ${dartName(path.slice(1))}Curve = Cubic(${a}, ${b}, ${c}, ${d});`)
    }
  }

  const sansFamily = typography.font.family.sans.$flutter ?? "Inter"
  const monoFamily = typography.font.family.mono.$flutter ?? "RobotoMono"

  write(
    "flutter/medusa_tokens.dart",
    `// ${BANNER.split("\n").join("\n// ")}

import 'package:flutter/widgets.dart';

/// Colours for the dark theme (the product default).
class MedusaColorsDark {
  const MedusaColorsDark._();
${colorLines.dark.join("\n")}
}

/// Colours for the light theme.
class MedusaColorsLight {
  const MedusaColorsLight._();
${colorLines.light.join("\n")}
}

/// Sizing, spacing, radii and the type ramp — identical across themes.
class MedusaSizes {
  const MedusaSizes._();
${dims.join("\n")}

  static const fontFamilySans = '${sansFamily}';
  static const fontFamilyMono = '${monoFamily}';
}

/// Motion. Wrap every animation so it collapses to [Duration.zero] when the
/// platform reports \`disableAnimations\`.
class MedusaMotion {
  const MedusaMotion._();
${durations.join("\n")}

  static Duration respecting(BuildContext context, Duration d) =>
      MediaQuery.maybeOf(context)?.disableAnimations ?? false ? Duration.zero : d;
}
`,
  )

  write(
    "flutter/medusa_theme.dart",
    `// ${BANNER.split("\n").join("\n// ")}

import 'package:flutter/material.dart';

import 'medusa_tokens.dart';

/// Ready-made [ThemeData] built from the shared tokens, so Flutter and the web
/// app render the same palette, radii and type ramp from one source of truth.
class MedusaTheme {
  const MedusaTheme._();

  static ThemeData get dark => _build(
        brightness: Brightness.dark,
        bg0: MedusaColorsDark.bg0,
        bg1: MedusaColorsDark.bg1,
        bg2: MedusaColorsDark.bg2,
        bg3: MedusaColorsDark.bg3,
        fg0: MedusaColorsDark.fg0,
        fg2: MedusaColorsDark.fg2,
        accent: MedusaColorsDark.accentHi,
        onAccent: MedusaColorsDark.onAccentBase,
        crit: MedusaColorsDark.critBase,
        line: MedusaColorsDark.line2,
      );

  static ThemeData get light => _build(
        brightness: Brightness.light,
        bg0: MedusaColorsLight.bg0,
        bg1: MedusaColorsLight.bg1,
        bg2: MedusaColorsLight.bg2,
        bg3: MedusaColorsLight.bg3,
        fg0: MedusaColorsLight.fg0,
        fg2: MedusaColorsLight.fg2,
        accent: MedusaColorsLight.accentHi,
        onAccent: MedusaColorsLight.onAccentBase,
        crit: MedusaColorsLight.critBase,
        line: MedusaColorsLight.line2,
      );

  static ThemeData _build({
    required Brightness brightness,
    required Color bg0,
    required Color bg1,
    required Color bg2,
    required Color bg3,
    required Color fg0,
    required Color fg2,
    required Color accent,
    required Color onAccent,
    required Color crit,
    required Color line,
  }) {
    final scheme = ColorScheme(
      brightness: brightness,
      primary: accent,
      onPrimary: onAccent,
      secondary: bg3,
      onSecondary: fg0,
      error: crit,
      onError: onAccent,
      surface: bg2,
      onSurface: fg0,
    );

    return ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: scheme,
      scaffoldBackgroundColor: bg0,
      fontFamily: MedusaSizes.fontFamilySans,
      textTheme: TextTheme(
        displaySmall: TextStyle(
          fontSize: MedusaSizes.fontSize3xl,
          fontWeight: MedusaSizes.fontWeightSemibold,
          letterSpacing: MedusaSizes.fontTrackingTight * MedusaSizes.fontSize3xl,
          color: fg0,
        ),
        titleLarge: TextStyle(
          fontSize: MedusaSizes.fontSize2xl,
          fontWeight: MedusaSizes.fontWeightSemibold,
          letterSpacing: MedusaSizes.fontTrackingSnug * MedusaSizes.fontSize2xl,
          color: fg0,
        ),
        bodyMedium: TextStyle(
          fontSize: MedusaSizes.fontSizeBase,
          height: MedusaSizes.fontLineHeightRelaxed,
          color: fg2,
        ),
      ),
      inputDecorationTheme: InputDecorationTheme(
        filled: true,
        fillColor: bg1,
        contentPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(MedusaSizes.radiusMd),
          borderSide: BorderSide(color: line),
        ),
        enabledBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(MedusaSizes.radiusMd),
          borderSide: BorderSide(color: line),
        ),
        focusedBorder: OutlineInputBorder(
          borderRadius: BorderRadius.circular(MedusaSizes.radiusMd),
          borderSide: BorderSide(color: accent, width: 1.5),
        ),
      ),
      filledButtonTheme: FilledButtonThemeData(
        style: FilledButton.styleFrom(
          backgroundColor: accent,
          foregroundColor: onAccent,
          minimumSize: const Size.fromHeight(MedusaSizes.sizeControl),
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(MedusaSizes.radiusMd),
          ),
          textStyle: const TextStyle(
            fontSize: MedusaSizes.fontSizeLg,
            fontWeight: MedusaSizes.fontWeightSemibold,
          ),
        ),
      ),
      cardTheme: CardThemeData(
        color: bg2,
        elevation: 0,
        shape: RoundedRectangleBorder(
          side: BorderSide(color: line),
          borderRadius: BorderRadius.circular(MedusaSizes.radiusLg),
        ),
      ),
    );
  }
}
`,
  )

  const iconEntries = Object.entries(icons.icons).map(([name, parts]) => {
    const items = parts.map((p) => {
      if (p.path) return `MedusaIconPath(${JSON.stringify(p.path)})`
      if (p.circle) return `MedusaIconCircle(${p.circle.join(", ")})`
      if (p.rect) return `MedusaIconRect(${p.rect.join(", ")})`
      return null
    })
    return `  '${name}': [${items.filter(Boolean).join(", ")}],`
  })

  write(
    "flutter/medusa_icons.dart",
    `// ${BANNER.split("\n").join("\n// ")}

/// The shared stroke icon set, as drawing primitives on a
/// ${icons.meta.viewBox}x${icons.meta.viewBox} canvas. Render with a CustomPainter using
/// PaintingStyle.stroke, StrokeCap.round and StrokeJoin.round.
sealed class MedusaIconPart {
  const MedusaIconPart();
}

class MedusaIconPath extends MedusaIconPart {
  final String d;
  const MedusaIconPath(this.d);
}

class MedusaIconCircle extends MedusaIconPart {
  final double cx, cy, r;
  const MedusaIconCircle(this.cx, this.cy, this.r);
}

class MedusaIconRect extends MedusaIconPart {
  final double x, y, width, height, radius;
  const MedusaIconRect(this.x, this.y, this.width, this.height, this.radius);
}

class MedusaIcons {
  const MedusaIcons._();

  static const double viewBox = ${icons.meta.viewBox};
  static const double defaultStrokeWidth = ${icons.meta.defaultStrokeWidth};

  static const Map<String, List<MedusaIconPart>> all = {
${iconEntries.join("\n")}
  };
}
`,
  )
}

/* ── go ─────────────────────────────────────────────────────────── */

console.log("Building Medusa design system…")
buildCss()
buildTs()
buildFlutter()
console.log("Done.")
